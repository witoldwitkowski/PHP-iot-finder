const MAX_HEAD: usize = 16 * 1024;
const MAX_BODY: usize = 64 * 1024;
const COOKIE: &str = "iotscan_token";

static INDEX: &str = include_str!("../../assets/index.html");
static APP_JS: &str = include_str!("../../assets/app.js");
static UI_CSS: &str = include_str!("../../assets/ui.css");

/// A parsed request.
pub struct Req {
    /// Method.
    pub method: String,
    /// Path without the query.
    pub path: String,
    /// Raw query string.
    pub query: String,
    /// Headers (names lowercased).
    pub headers: Vec<(String, String)>,
    /// Body.
    pub body: Vec<u8>,
}

impl Req {
    /// Header lookup.
    pub fn header(&self, name: &str) -> Option<&str> {
        self.headers.iter().find(|(k, _)| k == name).map(|(_, v)| v.as_str())
    }
    /// Query parameter lookup (no percent-decoding needed for our keys).
    pub fn query_param(&self, key: &str) -> Option<&str> {
        self.query.split('&').find_map(|kv| kv.split_once('=').filter(|(k, _)| *k == key).map(|(_, v)| v))
    }
}

/// A response.
pub struct Resp {
    /// Status code.
    pub status: u16,
    /// Content type.
    pub ctype: &'static str,
    /// Body.
    pub body: Vec<u8>,
    /// Extra headers.
    pub headers: Vec<(String, String)>,
}

impl Resp {
    /// Build a response.
    pub fn new(status: u16, ctype: &'static str, body: impl Into<Vec<u8>>) -> Resp {
        Resp { status, ctype, body: body.into(), headers: vec![] }
    }
    /// JSON body.
    pub fn json(status: u16, v: &impl serde::Serialize) -> Resp {
        Resp::new(status, "application/json; charset=utf-8", serde_json::to_vec(v).unwrap_or_else(|_| b"{}".to_vec()))
    }
    /// JSON `{ "error": msg }`.
    pub fn error(status: u16, msg: &str) -> Resp {
        Resp::json(status, &serde_json::json!({ "error": msg }))
    }
    /// Add a header.
    pub fn with(mut self, k: &str, v: &str) -> Resp {
        self.headers.push((k.to_string(), v.to_string()));
        self
    }
}

fn reason(status: u16) -> &'static str {
    match status {
        200 => "OK",
        202 => "Accepted",
        303 => "See Other",
        400 => "Bad Request",
        401 => "Unauthorized",
        403 => "Forbidden",
        404 => "Not Found",
        405 => "Method Not Allowed",
        409 => "Conflict",
        413 => "Payload Too Large",
        415 => "Unsupported Media Type",
        421 => "Misdirected Request",
        _ => "Error",
    }
}

fn serialize(r: Resp) -> Vec<u8> {
    let mut h = format!(
        "HTTP/1.1 {} {}\r\nContent-Type: {}\r\nContent-Length: {}\r\nConnection: close\r\n\
         Cache-Control: no-store\r\nX-Content-Type-Options: nosniff\r\nReferrer-Policy: no-referrer\r\n\
         X-Frame-Options: DENY\r\nCross-Origin-Resource-Policy: same-origin\r\nCross-Origin-Opener-Policy: same-origin\r\n\
         Permissions-Policy: camera=(), microphone=(), geolocation=()\r\n\
         Content-Security-Policy: default-src 'none'; script-src 'self'; style-src 'self'; img-src 'self' data:; connect-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'\r\n",
        r.status,
        reason(r.status),
        r.ctype,
        r.body.len()
    );
    for (k, v) in &r.headers {
        // Header values are generated by us, but never allow CR/LF through.
        if !k.contains(['\r', '\n']) && !v.contains(['\r', '\n']) {
            h.push_str(&format!("{k}: {v}\r\n"));
        }
    }
    h.push_str("\r\n");
    let mut out = h.into_bytes();
    out.extend_from_slice(&r.body);
    out
}

async fn read_request(s: &mut TcpStream) -> Result<Req, Resp> {
    let mut buf: Vec<u8> = Vec::with_capacity(2048);
    let mut chunk = [0u8; 2048];
    let (head_len, method, target, headers, content_len) = loop {
        let n = s.read(&mut chunk).await.map_err(|_| Resp::error(400, "read error"))?;
        if n == 0 {
            return Err(Resp::error(400, "empty request"));
        }
        buf.extend_from_slice(&chunk[..n]);
        if buf.len() > MAX_HEAD + MAX_BODY {
            return Err(Resp::error(413, "request too large"));
        }
        let mut hdrs = [httparse::EMPTY_HEADER; 48];
        let mut req = httparse::Request::new(&mut hdrs);
        match req.parse(&buf) {
            Ok(httparse::Status::Complete(off)) => {
                let headers: Vec<(String, String)> = req
                    .headers
                    .iter()
                    .map(|h| (h.name.to_ascii_lowercase(), String::from_utf8_lossy(h.value).trim().to_string()))
                    .collect();
                let cl = headers.iter().find(|(k, _)| k == "content-length").map(|(_, v)| v.parse::<usize>());
                let cl = match cl {
                    None => 0,
                    Some(Ok(n)) => n,
                    Some(Err(_)) => return Err(Resp::error(400, "bad content-length")),
                };
                if headers.iter().any(|(k, _)| k == "transfer-encoding") {
                    return Err(Resp::error(400, "chunked requests are not supported"));
                }
                break (off, req.method.unwrap_or("").to_string(), req.path.unwrap_or("/").to_string(), headers, cl);
            }
            Ok(httparse::Status::Partial) => {
                if buf.len() > MAX_HEAD {
                    return Err(Resp::error(413, "request head too large"));
                }
            }
            Err(_) => return Err(Resp::error(400, "malformed request")),
        }
    };
    if content_len > MAX_BODY {
        return Err(Resp::error(413, "body too large"));
    }
    while buf.len() < head_len + content_len {
        let n = s.read(&mut chunk).await.map_err(|_| Resp::error(400, "read error"))?;
        if n == 0 {
            return Err(Resp::error(400, "truncated body"));
        }
        buf.extend_from_slice(&chunk[..n]);
    }
    let body = buf[head_len..head_len + content_len].to_vec();
    let (path, query) = match target.split_once('?') {
        Some((p, q)) => (p.to_string(), q.to_string()),
        None => (target, String::new()),
    };
    Ok(Req { method, path, query, headers, body })
}

/// Authentication and request-origin checks shared by all routes.
pub struct Guard {
    /// The session token.
    pub token: String,
    /// The port we listen on.
    pub port: u16,
}

impl Guard {
    /// `Host` header must name this server on loopback.
    pub fn host_ok(&self, r: &Req) -> bool {
        r.header("host").is_some_and(|h| h == format!("127.0.0.1:{}", self.port) || h == format!("localhost:{}", self.port))
    }

    /// Token via cookie or explicit header.
    pub fn authed(&self, r: &Req) -> bool {
        if let Some(t) = r.header("x-iotscan-token")
            && ct_eq(t.as_bytes(), self.token.as_bytes())
        {
            return true;
        }
        r.header("cookie").is_some_and(|c| {
            c.split(';').filter_map(|p| p.trim().split_once('=')).any(|(k, v)| k == COOKIE && ct_eq(v.as_bytes(), self.token.as_bytes()))
        })
    }

    /// CSRF protection for mutating requests.
    pub fn csrf_ok(&self, r: &Req) -> Result<(), Resp> {
        let ctype = r.header("content-type").unwrap_or("");
        if !ctype.starts_with("application/json") {
            return Err(Resp::error(415, "content-type must be application/json"));
        }
        if let Some(o) = r.header("origin")
            && o != format!("http://127.0.0.1:{}", self.port)
            && o != format!("http://localhost:{}", self.port)
        {
            return Err(Resp::error(403, "cross-origin request refused"));
        }
        if let Some(site) = r.header("sec-fetch-site")
            && !matches!(site, "same-origin" | "none")
        {
            return Err(Resp::error(403, "cross-site request refused"));
        }
        Ok(())
    }
}

const LOCKED: &str = "<!doctype html><meta charset=utf-8><title>iotscan</title><body style=\"font:16px system-ui;max-width:34em;margin:4em auto;padding:0 1em\"><h1>Open the link from the terminal</h1><p>This page needs the one-time link printed when <code>iotscan gui</code> started. It contains a private token, which keeps other programs and websites from controlling your scanner.</p>";

/// Route one request.
pub async fn route(app: &Arc<App>, guard: &Guard, req: Req) -> Resp {
    if !guard.host_ok(&req) {
        return Resp::error(421, "unexpected Host header");
    }
    // Token hand-off: /?t=TOKEN sets the cookie and redirects to a clean URL.
    if req.method == "GET"
        && req.path == "/"
        && let Some(t) = req.query_param("t")
        && ct_eq(t.as_bytes(), guard.token.as_bytes())
    {
        return Resp::new(303, "text/plain", "")
            .with("Location", "/")
            .with("Set-Cookie", &format!("{COOKIE}={}; Path=/; HttpOnly; SameSite=Strict", guard.token));
    }
    if !guard.authed(&req) {
        return if req.path == "/" {
            Resp::new(401, "text/html; charset=utf-8", LOCKED)
        } else {
            Resp::error(401, "missing or invalid token")
        };
    }
    match (req.method.as_str(), req.path.as_str()) {
        ("GET", "/") | ("GET", "/index.html") => Resp::new(200, "text/html; charset=utf-8", INDEX),
        ("GET", "/app.js") => Resp::new(200, "text/javascript; charset=utf-8", APP_JS),
        ("GET", "/ui.css") => Resp::new(200, "text/css; charset=utf-8", UI_CSS),
        ("GET", p) if p.starts_with("/api/") => api::get(app, &req).await,
        ("POST", p) if p.starts_with("/api/") => {
            if let Err(r) = guard.csrf_ok(&req) {
                return r;
            }
            api::post(app, &req).await
        }
        ("GET" | "POST", _) => Resp::error(404, "not found"),
        _ => Resp::error(405, "method not allowed"),
    }
}

async fn handle(mut s: TcpStream, app: Arc<App>, guard: Arc<Guard>) {
    let resp = match tokio::time::timeout(Duration::from_secs(10), read_request(&mut s)).await {
        Ok(Ok(req)) => route(&app, &guard, req).await,
        Ok(Err(r)) => r,
        Err(_) => return,
    };
    let _ = tokio::time::timeout(Duration::from_secs(10), async {
        let _ = s.write_all(&serialize(resp)).await;
        let _ = s.shutdown().await;
    })
    .await;
}

/// Bind to loopback and serve until Ctrl-C or `/api/quit`.
pub async fn serve(args: GuiArgs, env: Arc<Environment>) -> std::io::Result<()> {
    let listener = TcpListener::bind(("127.0.0.1", args.port)).await?;
    Server::prepare(listener, args, env)?.run(true).await
}

/// A configured server, ready to run. Tests use this with port 0.
pub struct Server {
    listener: TcpListener,
    /// Shared application state.
    pub app: Arc<App>,
    guard: Arc<Guard>,
    quit: Arc<tokio::sync::Notify>,
    /// The URL (including the access token) that opens the GUI.
    pub url: String,
    args: GuiArgs,
}

impl Server {
    /// Generate the token and build the state.
    pub fn prepare(listener: TcpListener, args: GuiArgs, env: Arc<Environment>) -> std::io::Result<Server> {
        let port = listener.local_addr()?.port();
        let token = random_hex(16)?;
        let quit = Arc::new(tokio::sync::Notify::new());
        let app = App::new(args.clone(), env, quit.clone());
        let url = format!("http://127.0.0.1:{port}/?t={token}");
        Ok(Server { listener, app, guard: Arc::new(Guard { token, port }), quit, url, args })
    }

    /// Serve until quit. `announce` prints the URL, opens a browser and honours Ctrl-C.
    pub async fn run(self, announce: bool) -> std::io::Result<()> {
        if announce {
            eprintln!("iotscan GUI is running. Open:\n\n    {}\n\nPress Ctrl-C (or use Quit in the page) to stop.", self.url);
            if !self.args.no_open {
                open_browser(&self.url);
            }
        }
        let permits = Arc::new(Semaphore::new(32));
        loop {
            tokio::select! {
                _ = self.quit.notified() => break,
                _ = tokio::signal::ctrl_c(), if announce => break,
                acc = self.listener.accept() => {
                    let Ok((s, peer)) = acc else { continue };
                    if !peer.ip().is_loopback() {
                        continue;
                    }
                    let Ok(p) = permits.clone().try_acquire_owned() else { continue };
                    let (app, guard) = (self.app.clone(), self.guard.clone());
                    tokio::spawn(async move {
                        handle(s, app, guard).await;
                        drop(p);
                    });
                }
            }
        }
        self.app.shutdown();
        Ok(())
    }
}

fn open_browser(url: &str) {
    for opener in ["xdg-open", "sensible-browser", "gio"] {
        let mut cmd = std::process::Command::new(opener);
        if opener == "gio" {
            cmd.arg("open");
        }
        if cmd
            .arg(url)
            .stdin(std::process::Stdio::null())
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .spawn()
            .is_ok()
        {
            return;
        }
    }
    eprintln!("(could not launch a browser automatically; open the link above)");
}
